-- =====================================================================
-- EduNova · Esquema de base de datos (PostgreSQL / Supabase)
-- Se ejecuta con:  npm run db:init   (o pegándolo en Supabase → SQL Editor)
-- Los indicadores 0/1 (enable, active, is_read…) son SMALLINT: el backend los
-- entrega como true/false y acepta ambos al guardar.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS citext;

-- Tabla: Role
CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- Tabla: User
CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100),
    surname               VARCHAR(100),
    username              CITEXT NOT NULL UNIQUE,
    mail                  CITEXT NOT NULL UNIQUE,
    password              VARCHAR(255) NOT NULL,
    role_id               BIGINT,
    digital_signature     TEXT,
    profile_picture       VARCHAR(255),
    fcm_token             VARCHAR(512),
    two_factor_enabled    SMALLINT DEFAULT 0,
    two_factor_secret     VARCHAR(255),
    temp_2fa_code         VARCHAR(20),
    temp_2fa_expiry       BIGINT,
    enable                SMALLINT DEFAULT 1,
    terms_accepted_at     TIMESTAMP,
    privacy_accepted_at   TIMESTAMP,
    additional_admin      SMALLINT DEFAULT 0,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- Tabla: Student
CREATE TABLE students (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    surname               VARCHAR(100) NOT NULL,
    grade                 VARCHAR(50) NOT NULL,
    class_group           VARCHAR(50),
    previous_grade        VARCHAR(50),
    previous_class_group  VARCHAR(50),
    document_number       VARCHAR(20),
    active                SMALLINT NOT NULL DEFAULT 1
);

-- Tabla: Student
CREATE TABLE student_parents (
    student_id BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    PRIMARY KEY (student_id, user_id),
    CONSTRAINT fk_sp_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_sp_user    FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE
);

-- Tabla: Subject
CREATE TABLE subjects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    code            VARCHAR(20)  NOT NULL,
    level           VARCHAR(50)  NOT NULL,   -- 'primaria' | 'bachillerato' | 'media'
    grade_min       INT,
    grade_max       INT,
    hours_per_week  INT,
    credits         INT,
    type            VARCHAR(20),
    description     VARCHAR(500),
    teacher_id      BIGINT NULL,
    CONSTRAINT fk_subjects_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
);

-- Tabla: SubjectGrade
CREATE TABLE subject_grades (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT,
    teacher_id    BIGINT,
    subject_name  VARCHAR(150) NOT NULL,
    subject_id    BIGINT,
    period        INT NOT NULL,
    grade_name    VARCHAR(100),
    grade_value   DOUBLE PRECISION,
    is_evaluation SMALLINT,
    appreciative  VARCHAR(50),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT fk_sg_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_sg_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_sg_student_period_subject ON subject_grades (student_id, period, subject_name);

-- Tabla: ParentClass
CREATE TABLE parent_classes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade     VARCHAR(50) NOT NULL,
    classroom VARCHAR(50) NOT NULL,
    user_id   BIGINT NOT NULL,
    CONSTRAINT fk_pc_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Tabla: HomeroomAssignment
CREATE TABLE homeroom_assignments (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade     VARCHAR(50) NOT NULL,
    classroom VARCHAR(50) NOT NULL,
    user_id   BIGINT NULL,
    CONSTRAINT uq_homeroom_grade_classroom UNIQUE (grade, classroom),
    CONSTRAINT fk_ha_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Tabla: GradeColumnConfig
CREATE TABLE grade_column_configs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id       BIGINT NOT NULL,
    subject_name     VARCHAR(150) NOT NULL,
    grade            VARCHAR(50) NOT NULL,
    classroom        VARCHAR(50) NOT NULL,
    period           INT NOT NULL DEFAULT 1,
    columns_json     TEXT,
    quizzes_pct      INT DEFAULT 0,
    talleres_pct     INT DEFAULT 0,
    actividades_pct  INT DEFAULT 0,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP,
    CONSTRAINT uq_gcc UNIQUE (teacher_id, subject_name, grade, classroom, period),
    CONSTRAINT fk_gcc_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
);

-- Tabla: Period
CREATE TABLE academic_periods (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_number      INT NOT NULL UNIQUE,
    is_unlocked        SMALLINT DEFAULT 0,
    start_date         TIMESTAMP,
    end_date           TIMESTAMP,
    unlock_date        TIMESTAMP,
    lock_date          TIMESTAMP,
    description        VARCHAR(255),
    is_automatic       SMALLINT DEFAULT 0,
    notified_open_7d   SMALLINT DEFAULT 0,
    notified_close_7d  SMALLINT DEFAULT 0
);

-- Tabla: SchoolYearConfig
CREATE TABLE school_year_config (
    id                             BIGINT PRIMARY KEY,
    year_end_date                  DATE,
    min_passing_grade              DOUBLE PRECISION DEFAULT 3.5,
    current_academic_year          INT,
    last_wiped_at                  TIMESTAMP,
    last_advanced_at               TIMESTAMP,
    advance_pending_classroom_org  SMALLINT DEFAULT 0,
    year_end_notified              SMALLINT DEFAULT 0,
    year_end_7d_notified           SMALLINT DEFAULT 0
);

-- Tabla: ReportCard
CREATE TABLE report_cards (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          BIGINT,
    academic_period     VARCHAR(50),
    grades              TEXT,
    comments            TEXT,
    difficulties        TEXT,
    lost_areas          TEXT,
    pdf_url             VARCHAR(500),
    created_at          TIMESTAMP,
    sent_at             TIMESTAMP,
    teacher_id          BIGINT,
    homeroom_teacher    VARCHAR(150),
    created_by          BIGINT,
    is_signed           SMALLINT DEFAULT 0,
    signature_date      TIMESTAMP,
    principal_signature TEXT,
